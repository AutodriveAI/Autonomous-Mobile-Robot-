import os
import re

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription, SetEnvironmentVariable
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import EnvironmentVariable, LaunchConfiguration
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue
import xacro


def build_robot_description(robot_xacro_path):
    """Expand Xacro into a clean robot_description string for Gazebo.

    Gazebo and robot_state_publisher both receive the robot model through the
    robot_description ROS parameter. On this Humble/Gazebo Classic setup, raw
    xacro command output can include the XML declaration and generated comments:

        <?xml version="1.0" ?>
        <!-- autogenerated by xacro ... -->

    Those comments are normally harmless, but a compact parameter string is
    easier for launch tools and Gazebo plugins to transport safely:

      - no XML declaration
      - no XML comments
      - no unnecessary newlines

    The robot model content is still generated from the same robot.urdf.xacro.
    This only cleans the transport string used as the ROS parameter. The robot
    model content is still generated from the same robot.urdf.xacro.
    """
    document = xacro.process_file(robot_xacro_path)

    robot_xml = document.toxml()
    robot_xml = re.sub(r'<\?xml[^>]*\?>', '', robot_xml)
    robot_xml = re.sub(r'<!--.*?-->', '', robot_xml, flags=re.DOTALL)
    robot_xml = re.sub(r'\s+', ' ', robot_xml).strip()
    return robot_xml


def generate_launch_description():
    package_share = get_package_share_directory('amr_description')
    gazebo_ros_share = get_package_share_directory('gazebo_ros')
    package_share_parent = os.path.dirname(package_share)

    robot_xacro_path = os.path.join(package_share, 'urdf', 'robot.urdf.xacro')
    default_world_path = os.path.join(package_share, 'worlds', 'simple_home.world')

    robot_description = ParameterValue(
        build_robot_description(robot_xacro_path),
        value_type=str,
    )

    world = LaunchConfiguration('world')
    use_sim_time = LaunchConfiguration('use_sim_time')
    extra_gazebo_model_path = LaunchConfiguration('extra_gazebo_model_path')

    gazebo = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(
            os.path.join(gazebo_ros_share, 'launch', 'gazebo.launch.py')
        ),
        launch_arguments={
            'world': world,
        }.items(),
    )

    robot_state_publisher = Node(
        package='robot_state_publisher',
        executable='robot_state_publisher',
        name='robot_state_publisher',
        output='screen',
        parameters=[
            {
                'robot_description': robot_description,
                'use_sim_time': use_sim_time,
            }
        ],
    )

    spawn_robot = Node(
        package='gazebo_ros',
        executable='spawn_entity.py',
        name='spawn_amr',
        output='screen',
        arguments=[
            '-topic', 'robot_description',
            '-entity', 'amr',
            '-x', '0.0',
            '-y', '0.0',
            '-z', '0.03441',
        ],
    )

    return LaunchDescription([
        SetEnvironmentVariable(
            name='GAZEBO_MODEL_DATABASE_URI',
            value='',
        ),
        SetEnvironmentVariable(
            name='GAZEBO_MODEL_PATH',
            value=[
                package_share_parent,
                ':',
                extra_gazebo_model_path,
                ':',
                '/usr/share/gazebo-11/models',
                ':',
                EnvironmentVariable('GAZEBO_MODEL_PATH', default_value=''),
            ],
        ),
        DeclareLaunchArgument(
            'world',
            default_value=default_world_path,
            description='Gazebo world file to load.',
        ),
        DeclareLaunchArgument(
            'use_sim_time',
            default_value='true',
            description='Use Gazebo simulation time.',
        ),
        DeclareLaunchArgument(
            'extra_gazebo_model_path',
            default_value='',
            description=(
                'Optional extra Gazebo model directory. Use this when loading '
                'an external world that contains model:// references, for '
                'example the turtlebot3_gazebo/models folder.'
            ),
        ),
        gazebo,
        robot_state_publisher,
        spawn_robot,
    ])
